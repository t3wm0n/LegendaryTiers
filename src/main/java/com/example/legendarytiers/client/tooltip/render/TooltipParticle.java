package com.example.legendarytiers.client.tooltip.render;

public final class TooltipParticle {

    public final float x;
    public final float y;
    public final float size;
    public final int color;

    public TooltipParticle(
            float x,
            float y,
            float size,
            int color
    ) {
        this.x = x;
        this.y = y;
        this.size = size;
        this.color = color;
    }
}